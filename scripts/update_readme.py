#!/usr/bin/env python
"""Insert the measured results and hardware tables into README.md (between the RESULTS/HARDWARE markers).

Everything comes from files written by the pipeline (results/metrics.json, results/comparison_table.md,
outputs/*/train_metrics.json, outputs/gguf/*-manifest.json, data/processed/*stats.json), so the README can never
drift from the actual run.

Usage:
    uv run python scripts/update_readme.py
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from clinical_tuner.config import add_config_args, load_config
from clinical_tuner.utils import PROJECT_ROOT, resolve


def _load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def _replace(text: str, marker: str, body: str) -> str:
    pattern = re.compile(rf"(<!-- {marker}:START -->)(.*?)(<!-- {marker}:END -->)", re.S)
    if not pattern.search(text):
        raise SystemExit(f"README is missing the {marker} markers")
    return pattern.sub(lambda m: f"{m.group(1)}\n{body.strip()}\n{m.group(3)}", text)


def results_block(cfg) -> str:
    rdir = resolve(cfg.project.results_dir)
    if not (rdir / "comparison_table.md").exists():
        return "_Results are generated by `bash scripts/run_full_pipeline.sh`._"
    table = (rdir / "comparison_table.md").read_text()
    main = table.split("## By data source")[0]
    main = re.sub(r"^# Results: base vs fine-tuned\n", "", main).replace("## ", "#### ")
    metrics = _load(rdir / "metrics.json") or {}
    m = metrics.get("models", {})
    headline = []

    def get(model, task, key):
        v = m.get(model, {}).get("by_task", {}).get(task, {}).get(key)
        return v["mean"] if isinstance(v, dict) else v

    chain = [x for x in ("base", "sft", "orpo") if x in m]
    if len(chain) > 1:
        for task, key, label in (("entities", "entity_f1_relaxed", "entity F1"),
                                 ("soap", "rougeL", "SOAP ROUGE-L"), ("summary", "rougeL", "summary ROUGE-L")):
            vals = [get(x, task, key) for x in chain]
            if all(v is not None for v in vals):
                headline.append(f"{label} " + " → ".join(f"{v:.3f}" for v in vals))
    names = {"base": "base", "sft": "SFT", "orpo": "SFT+ORPO"}
    judged = []
    for k, v in ((metrics.get("judge") or {}).get("pairwise") or {}).items():
        a, b = k.split("_vs_")
        judged.append(f"{names.get(a, a)} vs {names.get(b, b)} {100 * v['win']:.0f}/{100 * v['tie']:.0f}/"
                      f"{100 * v['loss']:.0f}")
    if judged:
        headline.append("LLM-judge pairwise win/tie/loss %: " + "; ".join(judged))
    split = _load(resolve(cfg.data.processed_dir) / "split_stats.json") or {}
    intro = (f"**Headline ({' → '.join(names[x] for x in chain)}):** " + "; ".join(headline) + ".\n\n"
             if headline else "")
    if split:
        intro += (f"Dataset: {split['total_encounters']:,} encounters / {split['total_examples']:,} examples "
                  f"({100 * split['achieved_synthetic_fraction']:.0f}% synthetic). ")
    figure = ""
    if (rdir / "figures" / "key_metrics_light.png").exists():
        figure = ('<picture>\n  <source media="(prefers-color-scheme: dark)" '
                  'srcset="results/figures/key_metrics_dark.png">\n  <img alt="Key test-set metrics for base, SFT, '
                  'SFT+ORPO and the Q4_K_M GGUF, with 95% bootstrap CIs" '
                  'src="results/figures/key_metrics_light.png">\n</picture>\n\n')
    return (intro.rstrip() + "\n\n" + figure + "Full per-source breakdown: [results/comparison_table.md](results/comparison_table.md); "
            "raw numbers: [results/metrics.json](results/metrics.json); side-by-side generations: "
            "[results/sample_outputs.md](results/sample_outputs.md).\n\n" + main)


def _val_name(tag: str) -> str:
    if tag == "sft":
        return "SFT"
    if tag == "orpo_trlnll":
        return "SFT + ORPO λ=0.1, TRL's NLL over prompt + response"
    if tag.startswith("orpo_l"):
        return f"SFT + ORPO λ={tag[len('orpo_l'):]}"
    return tag


def selection_block(cfg) -> str:
    m = _load(resolve(cfg.project.results_dir) / "metrics_val.json")
    if not m:
        return "_Run `scripts/tune_orpo.sh` to populate._"
    judge = m.get("judge") or {}
    meta = m.get("meta", {})
    cols = [("summary", "rougeL"), ("soap", "rougeL"), ("entities", "entity_f1_relaxed"),
            ("entities", "negation_accuracy")]
    lines = [f"Validation split: {meta.get('test_examples')} examples from {meta.get('test_encounters')} encounters "
             "(never used for training or for test reporting). Judge: pairwise against SFT, both presentation orders.\n",
             "| Model | Summary ROUGE-L | SOAP ROUGE-L | Entity F1 (relaxed) | Negation acc. | Judge overall (1-5) | "
             "vs SFT win / tie / loss |", "|---|---|---|---|---|---|---|"]
    order = ["sft", *sorted(t for t in m.get("models", {}) if t != "sft")]
    for tag in order:
        bt = m["models"][tag]["by_task"]
        vals = []
        for task, key in cols:
            v = bt.get(task, {}).get(key)
            v = v["mean"] if isinstance(v, dict) else v
            vals.append("-" if v is None else f"{v:.3f}")
        ab = (judge.get("absolute", {}).get(tag) or {}).get("overall")
        ab = f"{ab['mean']:.2f}" if isinstance(ab, dict) else "-"
        pr = judge.get("pairwise", {}).get(f"{tag}_vs_sft")
        pr = f"{100 * pr['win']:.0f}% / {100 * pr['tie']:.0f}% / {100 * pr['loss']:.0f}%" if pr else "-"
        lines.append(f"| {_val_name(tag)} | " + " | ".join(vals) + f" | {ab} | {pr} |")
    return "\n".join(lines)


def data_block(cfg) -> str:
    qs = _load(resolve(cfg.data.filtered_dir) / "quality_stats.json") or {}
    split = _load(resolve(cfg.data.processed_dir) / "split_stats.json") or {}
    val = _load(resolve(cfg.data.processed_dir) / "validation_report.json") or {}
    if not qs:
        return "_Run the data stage to populate._"
    rows = ["| Source | Candidates | Rejected by rules | Rejected by critic | Accepted | Used (70/30 mix) |",
            "|---|---|---|---|---|---|"]
    used = {}
    for counts in (split.get("by_split_source") or {}).values():
        for src, n in counts.items():
            used[src] = used.get(src, 0) + n
    for src, f in qs.get("funnel_by_source", {}).items():
        total = sum(f.values())
        rows.append(f"| {src} | {total} | {f.get('rejected_rules', 0)} | {f.get('rejected_critic', 0)} | "
                    f"{f.get('accepted', 0)} | {used.get(src, 0)} |")
    lines = [f"Final dataset: **{split.get('total_encounters', 0):,} encounters -> {split.get('total_examples', 0):,} "
             f"instruction examples**, {100 * split.get('achieved_synthetic_fraction', 0):.0f}% synthetic, split by "
             f"encounter (train/val/pref/test = {split.get('split_sizes_encounters')}).\n", *rows, ""]
    for name in ("critic_canary.json", "critic_canary_judge.json"):
        c = _load(resolve(cfg.data.filtered_dir) / name)
        if c:
            lines.append(f"* Critic `{c['critic']}` canary: {100 * c['detection_rate']:.0f}% of {c['n_corrupted']} "
                         f"injected errors caught, {100 * c['clean_false_reject_rate']:.0f}% of {c['n_clean']} clean "
                         "records rejected.")
    if val:
        lines.append(f"* `scripts/validate_dataset.py`: **{'PASSED' if val.get('ok') else 'FAILED'}** "
                     f"({len(val.get('errors', []))} errors) - no encounter or near-duplicate note shared between "
                     "test and training, prompts byte-identical to the serving prompt builder, all gold entities "
                     "grounded in their notes, no identifier patterns.")
    lines.append("* Full details: [data/DATA_CARD.md](data/DATA_CARD.md); human-review sample: "
                 "[data/review/review_sample.md](data/review/review_sample.md).")
    return "\n".join(lines)


def hardware_block(cfg) -> str:
    rows, peaks = [], []
    for stage, path in (("SFT", resolve(cfg.sft.output_dir) / "train_metrics.json"),
                        ("ORPO", resolve(cfg.orpo.output_dir) / "train_metrics.json")):
        t = _load(path)
        if t:
            peaks.append(float(t.get("peak_reserved_gb") or 0))
            n = t.get("train_examples") or t.get("train_pairs")
            rows.append(f"| {stage} | {t.get('gpu', '?')} | {t.get('peak_reserved_gb', '?')} GB | "
                        f"{t['train_seconds'] / 60:.0f} min | {n:,} {'examples' if stage == 'SFT' else 'pairs'}, "
                        f"{t['global_steps']} steps |")
    lines = ["Measured on this project's reference run (one GPU per training stage):\n",
             "| Stage | GPU | Peak VRAM (reserved) | Wall time | Workload |", "|---|---|---|---|---|", *rows]
    manifest = next(iter(sorted(resolve(cfg.export.output_dir).glob("*-manifest.json"))), None)
    if manifest:
        files = _load(manifest)["files"]
        lines.append("\nGGUF sizes: " + ", ".join(f"{q} {v['size_gb']:.2f} GB" for q, v in files.items()) + ".")
    peak = max(peaks) if peaks else None
    if peak is not None and peak <= 22:
        fit = (f"* **Training** peaked at {peak:.1f} GB (reserved by PyTorch, measured on the GPU above), inside the "
               "budget of a single **24 GB** card (RTX 3090/4090/A5000) with the default settings. On 16 GB, use "
               "`--set sft.per_device_batch_size=1 --set sft.gradient_accumulation_steps=16` (same effective batch) "
               "for SFT.\n")
    else:
        fit = (f"* **Training** peaked at {peak or 0:.1f} GB with the default batch size; on a 24 GB GPU use "
               "`--set sft.per_device_batch_size=1 --set sft.gradient_accumulation_steps=16` (same effective "
               "batch) and the matching `orpo.*` settings.\n")
    lines.append(
        "\n" + fit +
        "* **Inference** of the Q4_K_M GGUF needs ~6 GB of GPU memory (or runs on CPU / Apple Silicon via Ollama).\n"
        "* **Data generation and judging** use larger local models: the Qwen3-32B teacher/critic and the Qwen2.5-72B "
        "judge run in FP8 on 2×48 GB GPUs. With less hardware, point the `teacher`/`judge` endpoints at smaller "
        "models (e.g. Qwen3-14B) - the pipeline only needs OpenAI-compatible URLs.")
    return "\n".join(lines)


def main() -> None:
    parser = add_config_args(argparse.ArgumentParser(description=__doc__))
    args = parser.parse_args()
    cfg = load_config(args.config, args.overrides)
    readme = PROJECT_ROOT / "README.md"
    text = readme.read_text()
    text = _replace(text, "RESULTS", results_block(cfg))
    text = _replace(text, "HARDWARE", hardware_block(cfg))
    text = _replace(text, "DATA", data_block(cfg))
    if "<!-- SELECTION:START -->" in text:
        text = _replace(text, "SELECTION", selection_block(cfg))
    readme.write_text(text)
    print("README.md updated")


if __name__ == "__main__":
    main()
