#!/usr/bin/env python
"""Export the final merged model to GGUF (Q4_K_M and Q5_K_M by default) and write the Ollama Modelfile.

Steps (all local):
  1. Clone llama.cpp at a pinned ref into third_party/ (if needed) and build ``llama-quantize`` (CPU-only).
  2. ``convert_hf_to_gguf.py`` -> F16 GGUF.
  3. ``llama-quantize`` -> each requested quantization.
  4. Write ``serving/ollama_modelfile`` whose SYSTEM prompt is byte-identical to the training system prompt
     (``clinical_tuner.prompts.SYSTEM_PROMPT``) and whose template reproduces the ChatML format used in training.
  5. Write a manifest with file sizes, SHA-256 checksums and a fingerprint of the source weights. Existing GGUF files
     are reused only if that fingerprint matches; after retraining they are rebuilt.

Usage:
    uv run python serving/export_gguf.py
    uv run python serving/export_gguf.py --merged outputs/sft/merged --name localclinical-sft
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import os
import shutil
import subprocess
import sys
from pathlib import Path

from clinical_tuner.config import add_config_args, load_config
from clinical_tuner.prompts import SYSTEM_PROMPT
from clinical_tuner.utils import PROJECT_ROOT, read_json, resolve, setup_logging, write_json

log = logging.getLogger("export_gguf")

# ChatML template mirroring Qwen2.5's chat template for system/user/assistant turns (no tools).
MODELFILE_TEMPLATE = '''# LocalClinical-Tuner - Ollama Modelfile (generated by serving/export_gguf.py; do not edit by hand)
# Usage:  ollama create {name} -f serving/ollama_modelfile  &&  ollama run {name}
# The SYSTEM prompt below is identical to the one used in training (src/clinical_tuner/prompts.py).
# For best results send the task instruction + note exactly as built by clinical_tuner.prompts.build_messages
# (the Gradio app does this for you).
FROM {gguf}

TEMPLATE """{{{{- if .System }}}}<|im_start|>system
{{{{ .System }}}}<|im_end|>
{{{{ end }}}}
{{{{- range $i, $_ := .Messages }}}}
{{{{- if eq .Role "user" }}}}<|im_start|>user
{{{{ .Content }}}}<|im_end|>
{{{{ else if eq .Role "assistant" }}}}<|im_start|>assistant
{{{{ .Content }}}}<|im_end|>
{{{{ end }}}}
{{{{- end }}}}<|im_start|>assistant
"""

SYSTEM """{system}"""

PARAMETER temperature 0
PARAMETER repeat_penalty 1.05
PARAMETER num_ctx 8192
PARAMETER num_predict 1536
PARAMETER stop "<|im_end|>"
PARAMETER stop "<|endoftext|>"
'''


def run(cmd: list[str], **kw) -> None:
    log.info("$ %s", " ".join(str(c) for c in cmd))
    subprocess.run(cmd, check=True, **kw)


def ensure_llama_cpp(path: Path, ref: str, skip_build: bool) -> Path:
    if not (path / "convert_hf_to_gguf.py").exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "--depth", "1", "--branch", ref, "https://github.com/ggml-org/llama.cpp", str(path)])
    quantize = shutil.which("llama-quantize")
    built = path / "build" / "bin" / "llama-quantize"
    if built.exists():
        return built
    if quantize:
        return Path(quantize)
    if skip_build:
        raise SystemExit("llama-quantize not found and --skip-build given")
    run(["cmake", "-S", str(path), "-B", str(path / "build"), "-DCMAKE_BUILD_TYPE=Release", "-DGGML_CUDA=OFF",
         "-DLLAMA_CURL=OFF", "-DLLAMA_BUILD_TESTS=OFF", "-DLLAMA_BUILD_EXAMPLES=OFF"])
    run(["cmake", "--build", str(path / "build"), "--target", "llama-quantize", "-j", str(min(32, os.cpu_count() or 4))])
    return built


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 24), b""):
            h.update(chunk)
    return h.hexdigest()


def model_fingerprint(merged: Path) -> str:
    """Cheap identity of the merged weights: name, size and 64 evenly spaced 1 MiB samples of every shard.

    Hashing ~15 GB in full is slow; sampling the whole file still changes whenever any trained projection changes
    (embeddings/norms alone are not LoRA targets, so sampling only the start of a shard would not).
    """
    h = hashlib.sha256()
    for shard in sorted(merged.glob("*.safetensors")):
        size = shard.stat().st_size
        h.update(f"{shard.name}:{size}".encode())
        with open(shard, "rb") as f:
            for i in range(64):
                f.seek(max(0, (size - (1 << 20)) * i // 63))
                h.update(f.read(1 << 20))
    return h.hexdigest()


def write_modelfile(gguf: Path, name: str, out: Path) -> None:
    rel = os.path.relpath(gguf, out.parent)
    out.write_text(MODELFILE_TEMPLATE.format(gguf=rel, name=name, system=SYSTEM_PROMPT), encoding="utf-8")
    log.info("Wrote %s (FROM %s)", out, rel)


def main() -> None:
    parser = add_config_args(argparse.ArgumentParser(description=__doc__,
                                                     formatter_class=argparse.RawDescriptionHelpFormatter))
    parser.add_argument("--merged", default=None, help="merged HF model dir (default: export.merged_model)")
    parser.add_argument("--name", default=None, help="file/model name prefix (default: export.model_name)")
    parser.add_argument("--out-dir", default=None)
    parser.add_argument("--skip-build", action="store_true")
    parser.add_argument("--keep-f16", action="store_true", help="keep the intermediate F16 GGUF")
    parser.add_argument("--no-modelfile", action="store_true")
    args = parser.parse_args()
    setup_logging()
    cfg = load_config(args.config, args.overrides)
    ec = cfg.export
    merged = resolve(args.merged or ec.merged_model)
    name = args.name or ec.model_name
    out_dir = resolve(args.out_dir or ec.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if not (merged / "config.json").exists():
        raise SystemExit(f"No merged model at {merged}; run training first")

    llama = resolve(ec.llama_cpp_dir)
    quantize = ensure_llama_cpp(llama, ec.llama_cpp_ref, args.skip_build)
    f16 = out_dir / f"{name}-f16.gguf"
    fingerprint = model_fingerprint(merged)
    manifest_path = out_dir / f"{name}-manifest.json"
    previous = read_json(manifest_path) if manifest_path.exists() else {}
    if previous.get("source_fingerprint") != fingerprint:  # new weights (or no record): never reuse old GGUFs
        stale = [out_dir / f"{name}-{q.lower()}.gguf" for q in ec.quantizations] + [f16]
        if any(x.exists() for x in stale):
            log.info("Source model changed since the last export - rebuilding GGUF files")
        for x in stale:
            x.unlink(missing_ok=True)
    if not f16.exists():
        run([sys.executable, str(llama / "convert_hf_to_gguf.py"), str(merged), "--outtype", "f16", "--outfile",
             str(f16)])
    files = {}
    for q in ec.quantizations:
        target = out_dir / f"{name}-{q.lower()}.gguf"
        if not target.exists():
            run([str(quantize), str(f16), str(target), q])
        files[q] = target
    if not args.keep_f16:
        f16.unlink(missing_ok=True)

    manifest = {q: {"file": str(p.relative_to(PROJECT_ROOT)), "size_gb": round(p.stat().st_size / 1024**3, 3),
                    "sha256": sha256(p)} for q, p in files.items()}
    write_json(manifest_path, {"source_model": str(merged), "source_fingerprint": fingerprint,
                               "llama_cpp_ref": ec.llama_cpp_ref, "files": manifest})
    log.info("GGUF files: %s", manifest)
    if not args.no_modelfile:
        write_modelfile(files[ec.modelfile_quant], name, PROJECT_ROOT / "serving" / "ollama_modelfile")


if __name__ == "__main__":
    main()
