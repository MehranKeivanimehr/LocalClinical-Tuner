"""Render data/DATA_CARD.md from the statistics written by each data stage (re-run after every stage)."""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from .config import Config
from .utils import read_jsonl, resolve


def _load(path: Path) -> Any:
    return json.loads(path.read_text()) if path.exists() else None


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def _cost(cfg: Config, usage: dict[str, dict[str, int]]) -> list[list[Any]]:
    rows = []
    for ident, u in usage.items():
        price = next((e.pricing for e in cfg.endpoints.values() if (e.label or e.model) == ident and e.pricing), None)
        cost = "local (no API cost)"
        if price:
            usd = (u.get("input_tokens", 0) * price.get("input", 0) + u.get("output_tokens", 0) * price.get("output", 0)
                   + u.get("cache_read_input_tokens", 0) * price.get("cache_read", 0)
                   + u.get("cache_creation_input_tokens", 0) * price.get("cache_write", 0)) / 1e6
            cost = f"${usd:,.2f}"
        rows.append([ident, f"{u.get('requests', 0):,}", f"{u.get('input_tokens', 0):,}",
                     f"{u.get('output_tokens', 0):,}", cost])
    return rows


def write_data_card(cfg: Config) -> Path:
    raw, filt, proc = resolve(cfg.data.raw_dir), resolve(cfg.data.filtered_dir), resolve(cfg.data.processed_dir)
    syn = _load(raw / "synthetic_stats.json") or {}
    hf = _load(raw / "hf_stats.json") or {}
    qs = _load(filt / "quality_stats.json") or {}
    split = _load(proc / "split_stats.json")
    accepted = read_jsonl(filt / "accepted.jsonl") if (filt / "accepted.jsonl").exists() else []

    L: list[str] = []
    L.append("# Data card - LocalClinical-Tuner clinical notes dataset\n")
    L.append("> Auto-generated by `data/quality_filter.py` / `scripts/prepare_dataset.py`. Do not edit by hand.\n")
    L.append("**Contains no real patient data.** Encounters are either (a) fully synthetic notes written by an LLM from "
             "sampled fictional scenarios, or (b) public, de-identified/role-played doctor-patient dialogues released "
             "under CC BY 4.0. Identifier patterns are scrubbed from public data and forbidden in synthetic data. "
             "Intended use: research on privacy-preserving clinical documentation models. **Not for clinical use.**\n")

    L.append("## Composition\n")
    target = cfg.data.composition
    L.append(f"Target mix: {target.synthetic_fraction:.0%} synthetic / {1 - target.synthetic_fraction:.0%} public "
             f"(target {target.total_encounters:,} encounters). Each encounter yields three task examples "
             "(summary, SOAP note, entity extraction).\n")
    if split:
        rows = [[s, *[split["by_split_source"].get(s, {}).get(src, 0) for src in split["sources"]],
                 sum(split["by_split_source"].get(s, {}).values())] for s in split["splits"]]
        L.append(_table(["split", *split["sources"], "total"], rows) + "\n")
        L.append(f"Final encounters: **{split['total_encounters']:,}** ({split['achieved_synthetic_fraction']:.1%} "
                 f"synthetic) -> **{split['total_examples']:,}** task examples. Splits are by encounter (no note "
                 "appears in two splits) and stratified by source.\n")
        if split.get("note"):
            L.append(f"_{split['note']}_\n")

    L.append("## Sources and licenses\n")
    rows = [["synthetic", "LocalClinical-Tuner (this repo)", "-", "Apache-2.0 (generated content)",
             qs.get("accepted_by_source", {}).get("synthetic", "-")]]
    for s in cfg.data.hf.sources:
        rows.append([s.name, f"[{s.hf_id}](https://huggingface.co/datasets/{s.hf_id})", f"[upstream]({s.upstream})",
                     s.license, qs.get("accepted_by_source", {}).get(s.name, "-")])
    L.append(_table(["source", "dataset", "upstream", "license", "accepted encounters"], rows) + "\n")
    L.append("Citations: " + " ".join(f"{s.name}: {s.citation}" for s in cfg.data.hf.sources) + "\n")
    L.append("**Excluded sources**\n")
    L.append(_table(["dataset", "reason"], [[e.name, e.reason] for e in cfg.data.hf.excluded]) + "\n")

    L.append("## Generation\n")
    ext = _load(raw / "external_stats.json") or {}
    syn_acc = [r for r in accepted if r["source"] not in {s.name for s in cfg.data.hf.sources}]
    if syn_acc:
        L.append("- Synthetic notes were written by: " + ", ".join(
            f"`{k}` ({v})" for k, v in Counter(r["provenance"]["note"] for r in syn_acc).most_common()) +
            " (accepted encounters). Each note is generated from a sampled scenario (`clinical_tuner.taxonomy`); "
            "labels are produced from the note text only. Prompts: `data/generate_synthetic_notes.py` (API), "
            "`data/make_external_batches.py` (chat-app batches), `src/clinical_tuner/teacher.py` (annotation).")
    if syn:
        L.append(f"- API generation: requested {syn.get('requested', 0):,}, generated {syn.get('generated', 0):,}, "
                 f"rejected at generation {syn.get('rejected_at_generation', 0):,} "
                 f"({', '.join(f'{k}: {v}' for k, v in syn.get('rejection_reasons', {}).items()) or 'none'}).")
    if ext:
        rej = {k.split(":", 1)[1]: v for k, v in ext.items() if k.startswith("rejected:")}
        L.append(f"- Imported (bring-your-own / chat-app) data: {ext.get('imported', 0):,} records from "
                 f"{ext.get('files', 0)} files by `{ext.get('generator_label')}` "
                 f"({ext.get('labels_provided', 0):,} with complete labels; the rest labelled locally); "
                 f"{ext.get('unparseable_lines', 0)} unparseable lines, rejected at import: {rej or 'none'}.")
    L.append("- Public data label reuse: ACI-Bench clinician notes -> SOAP labels (restructured, content reused); "
             "MTS-Dialog GENHX section text -> summary labels. All other labels generated by the teacher.\n")
    if accepted:
        prov: dict[str, Counter] = defaultdict(Counter)
        for r in accepted:
            for f in ("summary", "soap", "entities"):
                p = r["provenance"][f]
                kind = "reference" if p.startswith("reference:") and "restructured" not in p else \
                    "reference (restructured)" if "restructured" in p else f"generated ({p})"
                prov[f"{r['source']}|{f}"][kind] += 1
        rows = [[k.split("|")[0], k.split("|")[1], ", ".join(f"{a}: {b}" for a, b in v.items())]
                for k, v in sorted(prov.items())]
        L.append("**Label provenance (accepted encounters)**\n")
        L.append(_table(["source", "label", "provenance"], rows) + "\n")
        sy = [r for r in accepted if r["source"] == "synthetic"]
        if sy:
            for key in ("specialty", "style", "difficulty"):
                c = Counter(r["scenario"][key] for r in sy)
                L.append(f"**Synthetic {key} distribution** ({len(c)} values): "
                         + ", ".join(f"{k} {v}" for k, v in c.most_common()) + "\n")

    if hf:
        L.append("## Public-data cleaning\n")
        rows = [[s, *(v.get(k, 0) for k in ("loaded", "clean", "too_short", "too_long", "not_english",
                                             "exact_duplicate", "near_duplicate_public",
                                             "near_duplicate_synthetic", "labeled"))]
                for s, v in hf.get("by_source", {}).items()]
        L.append(_table(["source", "loaded", "clean", "too short", "too long", "non-English", "exact dup",
                         "near-dup (public)", "near-dup (synthetic)", "labeled"], rows) + "\n")
        gr = hf.get("grounding_repair") or {}
        if gr:
            L.append(f"Entity grounding repair (one feedback round asking the teacher to copy exact spans): attempted "
                     f"{gr.get('attempted', 0)}, improved {gr.get('improved', 0)} ({gr.get('fully_grounded', 0)} fully "
                     "grounded).\n")
        lr = _load(raw / "label_repair_stats.json")
        if lr:
            L.append(f"Critic-guided label repair (labels of critic-rejected public records rewritten from the dialogue "
                     f"using the critic's findings, then re-audited): attempted {lr.get('attempted', 0)}, repaired "
                     f"{lr.get('repaired', 0)}. Finding: reused MTS-Dialog GENHX section texts are written from the "
                     "original note, not from the dialogue, and frequently contain facts the dialogue never mentions; "
                     "the critic rejected most of them, so they were replaced by dialogue-grounded summaries.\n")
        L.append(f"PHI-pattern scrubbing at ingestion (replacements by type): {hf.get('phi_scrubbed', {})}; final sweep "
                 f"over notes and labels in the quality filter: {qs.get('phi_final_sweep', {})}. This is best-effort "
                 "defence in depth on already de-identified/role-played data, not a certified de-identification.\n")

    if qs:
        L.append("## Quality filtering (both sources)\n")
        L.append("Pipeline: global near-dedup -> rule-based clinical sanity checks -> independent LLM critic. "
                 f"Rules reject on any critical finding or > {cfg.data.quality.rules.max_major} major findings; the "
                 f"critic rejects on any critical error, overall < {cfg.data.quality.critic.min_overall}, or any "
                 f"dimension <= {cfg.data.quality.critic.min_dimension}. The critic for each record is the first of "
                 f"{cfg.data.quality.critic.endpoints} whose model did not generate that record.\n")
        rows = [[s, v.get("accepted", 0), v.get("rejected_dedup", 0), v.get("rejected_rules", 0),
                 v.get("rejected_critic", 0)] for s, v in qs.get("funnel_by_source", {}).items()]
        L.append(_table(["source", "accepted", "rejected: dedup", "rejected: rules", "rejected: critic"], rows) + "\n")
        for stage in ("rules", "critic"):
            reasons = qs.get("rejection_reasons", {}).get(stage, {})
            if reasons:
                L.append(f"**Top {stage} rejection reasons**: "
                         + ", ".join(f"`{k}` {v}" for k, v in list(reasons.items())[:12]) + "\n")
        if qs.get("rule_findings"):
            L.append("**All rule findings (check:severity -> count, including minor/non-rejecting)**: "
                     + ", ".join(f"`{k}` {v}" for k, v in qs["rule_findings"].items()) + "\n")
        if qs.get("critic_score_means"):
            L.append("**Critic mean scores (1-5)**: "
                     + ", ".join(f"{k} {v}" for k, v in qs["critic_score_means"].items()) + "\n")
            L.append(f"**Critic models used**: {qs.get('critic_models')}\n")
            L.append("**Critic error counts (severity:category)**: "
                     + ", ".join(f"`{k}` {v}" for k, v in list(qs.get("critic_error_counts", {}).items())[:15]) + "\n")

    for canary_file in ("critic_canary.json", "critic_canary_judge.json"):
        canary = _load(filt / canary_file)
        if not canary:
            continue
        L.append(f"**Critic canary (validating the validator), `{canary['critic']}`**: "
                 f"{canary['n_corrupted']} accepted records were re-submitted with injected errors (hallucinated "
                 "medication in summary or plan, flipped negation, dropped diagnosis); the critic rejected "
                 f"**{100 * canary['detection_rate']:.0f}%** of them and re-rejected "
                 f"{100 * canary['clean_false_reject_rate']:.0f}% of the {canary['n_clean']} clean originals "
                 f"(held-out sample). By error type: {canary['by_kind']}.\n")

    L.append("## Human review\n")
    L.append(f"A seeded, source-stratified random sample of {cfg.data.quality.review.n_accepted} accepted and "
             f"{cfg.data.quality.review.n_rejected} rejected encounters is exported to "
             f"`{cfg.data.review_dir}/review_sample.md` (readable checklist) and `review_sample.jsonl` (with empty "
             "`human_verdict` fields) for clinician spot-checks.\n")

    usage: dict[str, Counter] = defaultdict(Counter)
    for part in (syn.get("usage_cumulative", {}), hf.get("usage_this_run", {}), qs.get("critic_usage", {}),
                 ext.get("usage", {})):
        for ident, u in (part or {}).items():
            usage[ident].update(u)
    if usage:
        L.append("## Compute and API cost\n")
        L.append(_table(["model", "requests", "input tokens", "output tokens", "estimated cost"],
                        _cost(cfg, {k: dict(v) for k, v in usage.items()})) + "\n")

    L.append("## Known limitations\n")
    L.append("- Synthetic notes reflect the teacher model's view of clinical practice and may under-represent rare "
             "presentations, documentation errors, and real-world messiness.\n"
             "- Gold labels are model-generated (or reused references) and filtered automatically; they are not "
             "clinician-verified. Use the human-review sample to estimate residual error.\n"
             "- Public dialogues are role-played (ACI-Bench) or derived from sample reports (MTS-Dialog); they are "
             "short or US-centric and English-only.\n"
             "- When no API is available, public-data labels come from the local teacher and are criticized by the "
             "same model family that later serves as the evaluation judge (Qwen2.5-72B); it filtered, but did not "
             "write, any training data.\n"
             "- Rule checks are high-precision heuristics (regex extraction, a small curated drug table) and will "
             "miss errors that the critic must catch; the critic itself is an LLM and can be wrong.\n")
    path = resolve(cfg.data.data_card)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8")
    return path
